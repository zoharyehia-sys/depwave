import type { Explanation, ImpactReport, Reporter, TestPlan } from '@depwave/core';
import { renderWhy } from './WhyReporter.js';

/** Hidden marker that identifies depwave's comment, so CI edits it in place instead of posting a new one per push. */
export const COMMENT_MARKER = '<!-- depwave-impact -->';

const MAX_UNRESOLVED = 10;
const short = (rev: string) => (/^[0-9a-f]{40}$/.test(rev) ? rev.slice(0, 7) : rev);
const plural = (n: number, word: string) => `${n} ${word}${n === 1 ? '' : 's'}`;

/**
 * GitHub-flavoured Markdown for a PR comment: the headline number first, the details collapsed, and `depwave why`
 * paths for the top tests so reviewers see the reason, not only a list.
 */
export class MarkdownReporter implements Reporter {
  readonly format = 'markdown';

  constructor(private readonly explanations: readonly Explanation[] = []) {}

  render(report: ImpactReport, plan: TestPlan): string {
    const impacted = plan.groups.reduce((n, g) => n + g.tests.length, 0);
    const lines: string[] = [COMMENT_MARKER, `### 🌊 depwave: ${headline(impacted, plan)}`, ''];

    lines.push(
      '| | |',
      '|---|---|',
      `| Compared | \`${short(report.base)}\` (merge base) → \`${short(report.head)}\` |`,
      `| Changed files | ${report.changedFiles.length} |`,
      `| Impacted tests | **${impacted}**${plan.totalTests === undefined ? '' : ` of ${plan.totalTests}`} |`,
      `| Granularity | ${report.granularity} |`,
      '',
    );

    for (const trigger of report.globalTriggers) {
      const reach = trigger.scope === undefined ? 'every test runs' : `everything in ${plural(trigger.scope.length, 'package')} runs`;
      lines.push(`> [!NOTE]`, `> \`${trigger.path}\` changed (${trigger.kind}): ${reach}.`, '');
    }

    if (report.unresolved.length > 0) {
      lines.push('> [!WARNING]', `> ${plural(report.unresolved.length, 'import')} could not be resolved, so their dependents may be missing:`);
      for (const u of report.unresolved.slice(0, MAX_UNRESOLVED)) lines.push(`> - \`${u.from}\` → \`${u.specifier}\` (${u.reason})`);
      if (report.unresolved.length > MAX_UNRESOLVED) lines.push(`> - … and ${report.unresolved.length - MAX_UNRESOLVED} more`);
      lines.push('');
    }

    if (impacted > 0) {
      const changed = new Set(report.changedFiles);
      lines.push('#### Tests to run', '');
      for (const group of plan.groups) {
        lines.push(`<details><summary><b>${escapeHtml(group.packageName)}</b> (${group.runner}): ${plural(group.tests.length, 'file')}</summary>`, '');
        for (const test of group.tests) lines.push(`- \`${test}\`${changed.has(test) ? ' _(changed in this PR)_' : ''}`);
        lines.push('', '</details>', '');
      }
    }

    const shown = this.explanations.filter((e) => e.kind === 'impacted');
    if (shown.length > 0) {
      lines.push(`#### Why? (${shown.length === impacted ? 'every test' : `top ${plural(shown.length, 'test')}`})`, '');
      for (const explanation of shown) {
        const text = renderWhy(explanation, { base: report.base, head: report.head, granularity: report.granularity }).trimEnd();
        lines.push(`<details><summary><code>${escapeHtml(explanation.target)}</code></summary>`, '', '```text', text, '```', '', '</details>', '');
      }
    }

    // Inside a code span `<test>` renders literally (entities would not be decoded there).
    lines.push(`<sub>Run \`depwave why <test> --base ${short(report.base)}\` locally for any other test. Generated by depwave.</sub>`, '');
    return lines.join('\n');
  }
}

function headline(impacted: number, plan: TestPlan): string {
  if (plan.runAll) return `all ${plan.totalTests ?? impacted} test files (a global trigger fired)`;
  if (impacted === 0) return 'no test files impacted ✅';
  const total = plan.totalTests;
  const saved = total !== undefined && total > 0 ? ` of ${total} (${Math.round((1 - impacted / total) * 100)}% skipped)` : '';
  return `${plural(impacted, 'test file')} impacted${saved}`;
}

const escapeHtml = (text: string) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
